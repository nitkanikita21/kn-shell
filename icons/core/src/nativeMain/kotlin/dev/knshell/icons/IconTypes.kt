package dev.knshell.icons

/**
 * How an icon pack's SVG markup is supposed to be tinted and scaled.
 *
 * A pack is geometry plus a colouring convention. Most line libraries (Lucide,
 * Tabler, Feather) draw with `stroke`; Solid-style libraries draw with `fill`;
 * some (Handdrawn,duotone variants) only work untinted. The [IconPack] carries
 * one of these and [Icon] applies it.
 *
 * @param tintAttribute the SVG attribute that carries the colour — `"stroke"` or `"fill"`.
 * @param strokeWidth default `stroke-width` baked into generated documents; overridden
 *   per-call by `Icon(strokeWidth=…)` / [IconRef] consumers.
 * @param viewBoxSize the coordinate system the pack's markup is authored in (Lucide: 24).
 * @param viewBoxOverride full `viewBox` value for packs whose canvas is not `0 0 S S`
 * (Material Symbols draws in `0 -960 960 960`). When set it replaces the
 * [viewBoxSize]-derived box; [viewBoxSize] still sizes the `width`/`height`.
 */
data class IconStyle(
    val tintAttribute: String = "stroke",
    val strokeWidth: Double = 2.0,
    val viewBoxSize: Double = 24.0,
    val viewBoxOverride: String? = null,
)

/**
 * The adapter contract that makes an upstream icon set usable from KN-shell.
 *
 * Implementations are generated by the `dev.knshell.icons.pack` Gradle plugin
 * (see `icons-plugin/`); hand-written packs only need these three members.
 * [svgInner] must stay `internal`-fast: it is called on the render path and its
 * result is cached, so plain string lookup is enough — no parsing, no IO.
 */
interface IconPack {
    /** Stable identity used in cache keys and diagnostics, e.g. `"Lucide"`. */
    val name: String

    /** Tinting convention of this pack. */
    val style: IconStyle

    /**
     * Raw SVG body of icon [id] — everything between `<svg …>` and `</svg>`, or `null`
     * if the id is not part of this pack.
     *
     * Returning `null` is *not* an error: the [dev.knshell.compose.Icon] composable
     * then warns once per id to stderr and paints an empty slot, so an un-synced pack
     * can never crash the shell.
     */
    fun svgInner(id: String): String?
}

/**
 * A pack-qualified icon identifier — the value [dev.knshell.compose.Icon] consumes.
 *
 * Generated pack catalogs expose these as properties (`Lucide.Home`); [of] is the
 * escape hatch for runtime ids. Equality compares the id and the pack reference, so
 * two `IconRef`s of the same icon from the same pack object are identical.
 */
data class IconRef(val pack: IconPack, val id: String) {

    /** Tinting convention of the referenced pack. */
    val style: IconStyle get() = pack.style

    /** Raw SVG body, or `null` when the pack does not carry this id. */
    val source: String? get() = pack.svgInner(id)
}

/** Convenience for dynamic ids: `LucidePack.ref("home")`. */
fun IconPack.ref(id: String): IconRef = IconRef(this, id)
