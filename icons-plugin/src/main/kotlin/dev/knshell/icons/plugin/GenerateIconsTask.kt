package dev.knshell.icons.plugin

import java.io.File
import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.tasks.IgnoreEmptyDirectories
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputDirectory
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.Optional
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

/**
 * Generates the two Kotlin sources of a pack module:
 *
 * - `<Name>Catalog.generated.kt` — `object <Name>` with one typed `IconRef` per
 *   upstream icon (complete catalog: IDE completion always sees every icon);
 * - `<Name>Data.generated.kt` — the SVG *inner markup* strings for the icons the
 *   usage scan actually found (tree-shaken: unused icons cost nothing).
 *
 * The scan works on raw file globs, never on project dependencies, so a consumer
 * (:shell-app) can be scanned without depending back on the pack module.
 */
abstract class GenerateIconsTask : DefaultTask() {

    @get:Input val objectName: Property<String> = project.objects.property(String::class.java)
    @get:Input val packageName: Property<String> = project.objects.property(String::class.java)
    @get:Input val tintAttribute: Property<String> = project.objects.property(String::class.java)
    @get:Input val strokeWidth: Property<Double> = project.objects.property(Double::class.java)
    @get:Input val viewBoxSize: Property<Double> = project.objects.property(Double::class.java)
    /** Packs whose canvas is not `0 0 S S` (Material Symbols: `0 -960 960 960`). */
    @get:Input @get:Optional val viewBoxOverride: Property<String> = project.objects.property(String::class.java)
    @get:InputDirectory val cachedIcons: DirectoryProperty = project.objects.directoryProperty()
    /**
     * The Kotlin sources the usage scan reads. A real input file collection (not
     * a list of path strings), so adding `Icon(Lucide.Star)` anywhere in the
     * scanned roots re-runs codegen instead of silently tree-shaking it out.
     */
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    @get:IgnoreEmptyDirectories
    val scanSources: ConfigurableFileCollection = project.objects.fileCollection()
    @get:OutputDirectory val outputDir: DirectoryProperty = project.objects.directoryProperty()

    init {
        group = "icons"
        description = "Generate the icon catalog and tree-shaken SVG data."
    }

    @TaskAction
    fun generate() {
        val name = objectName.get()
        val pkg = packageName.get()
        val icons = File(cachedIcons.get().asFile, "icons")
        val ids = icons.walkTopDown()
            .filter { it.isFile && it.extension == "svg" }
            .map { it.nameWithoutExtension }
            .toSortedSet()
        require(ids.isNotEmpty()) { "[icons] no svg files under $icons — did syncIcons run?" }

        val entries = catalogEntries(ids)

        // 1. catalog: every upstream icon gets a typed reference.
        val catalog = StringBuilder()
        catalog.line("/* GENERATED by :icons-plugin (task generateIcons) — do not edit. */")
        catalog.line("@file:Suppress(\"RedundantVisibilityModifier\", \"unused\")")
        catalog.line()
        catalog.line("package $pkg")
        catalog.line()
        catalog.line("import dev.knshell.icons.IconRef")
        catalog.line()
        catalog.line("/**")
        catalog.line(" * $name — complete icon catalog (${entries.size} icons).")
        catalog.line(" *")
        catalog.line(" * Every upstream icon is addressable from the IDE; the SVG payload of an icon")
        catalog.line(" * is embedded only when the usage scan finds a reference to it (tree-shaking),")
        catalog.line(" * so adding `Icon($name.Something)` requires only a rebuild, never a manual list.")
        catalog.line(" */")
        catalog.line("object $name {")
        catalog.line(" /** All icon ids in this pack (generated catalog). */")
        catalog.line(" val ids: Set<String> = setOf(")
        ids.forEach { catalog.line(" \"$it\",") }
        catalog.line(" )")
        catalog.line()
        catalog.line(" private fun ref(id: String): IconRef = IconRef(${name}Pack, id)")
        catalog.line()
        for ((className, id) in entries) {
            catalog.line(" /** `$id` */ val $className: IconRef get() = ref(\"$id\")")
        }
        catalog.line()
        catalog.line(" /** Dynamic escape hatch — id must exist in [$name.ids]. */")
        catalog.line(" fun of(id: String): IconRef = ref(id)")
        catalog.line("}")
        write("${name}Catalog.generated.kt", catalog)

        // 2. usage scan: which icons does the codebase actually reference?
        val used = scanUsedIds(name, entries, ids)
        logger.lifecycle("[icons] $name: ${entries.size} catalog icons, ${used.size} referenced -> embedding")

        val data = StringBuilder()
        data.line("/* GENERATED by :icons-plugin (task generateIcons) — do not edit.")
        data.line(" * Tree-shaken SVG data: only icons referenced in the scanned sources.")
        data.line(" * Regenerated on every build; add an Icon($name.X) usage and rebuild to pack it. */")
        data.line("@file:Suppress(\"RedundantVisibilityModifier\")")
        data.line()
        data.line("package $pkg")
        data.line()
        data.line("/** SVG inner markup per icon id, exactly as upstream (no <svg> wrapper). */")
        data.line("internal object ${name}Data {")
        data.line(" fun inner(id: String): String? = when (id) {")
        for (id in used) {
            val raw = File(icons, "$id.svg").readText()
            data.line(" \"$id\" ->")
            emitStringLiteral(data, stripSvgWrapper(raw).trim())
            data.line()
        }
        data.line(" else -> null")
        data.line(" }")
        data.line("}")
        data.line()
        data.line("/** Pack implementation wired to the generated [${name}Data] and the declared style. */")
        data.line("internal object ${name}Pack : dev.knshell.icons.IconPack {")
        data.line(" override val name: String = \"$name\"")
        data.line(" override val style = dev.knshell.icons.IconStyle(")
        data.line(" tintAttribute = \"${tintAttribute.get()}\",")
        data.line(" strokeWidth = ${strokeWidth.get()},")
        data.line(" viewBoxSize = ${viewBoxSize.get()},")
            viewBoxOverride.orNull?.let { data.line("            viewBoxOverride = \"$it\",") }
        data.line(" )")
        data.line(" override fun svgInner(id: String): String? = ${name}Data.inner(id)")
        data.line("}")
        write("${name}Data.generated.kt", data)
    }

    private fun catalogEntries(ids: Set<String>): List<Pair<String, String>> =
        NameMapping.catalogEntries(ids)

private fun scanUsedIds(name: String, entries: List<Pair<String, String>>, ids: Set<String>): Set<String> {
        val classRef = Regex("\\b$name\\.([A-Z][A-Za-z0-9]*)")
        val ofRef = Regex("\\b$name\\.of\\(\"([^\"]+)\"\\)")
        val byClass = entries.toMap()
        val result = sortedSetOf<String>()
        val unknown = sortedSetOf<String>()
        for (file in scanSources.files.toList().sortedBy { it.absolutePath }) {
            if (!file.isFile || file.extension != "kt") continue
            val text = file.readText()
            classRef.findAll(text).forEach { m ->
                val id = byClass[m.groupValues[1]]
                if (id != null) result.add(id) else unknown.add("$name.${m.groupValues[1]}")
            }
            ofRef.findAll(text).forEach { m ->
                val id = m.groupValues[1]
                if (ids.contains(id)) result.add(id) else unknown.add("$name.of(\"$id\")")
            }
        }
        if (unknown.isNotEmpty()) {
            logger.warn("[icons] $name: ${unknown.size} unknown icon reference(s), ignored: ${unknown.take(10)}")
        }
        return result
    }

    /**
     * Everything between the `<svg …>` open tag and `</svg>`, with XML comments
     * removed. Comments matter: lucide-static files begin with a license comment
     * whose `-->` would otherwise be read as the end of the root tag, and the
     * attribution stays in the pack's own LICENSE instead of every icon string.
     */
    private fun stripSvgWrapper(raw: String): String {
        val cleaned = raw.replace(Regex("<!--.*?-->", RegexOption.DOT_MATCHES_ALL), "")
        val start = cleaned.indexOf("<svg")
        val open = cleaned.indexOf('>', start)
        val end = cleaned.lastIndexOf("</svg")
        return if (start >= 0 && open > start && end > open) cleaned.substring(open + 1, end) else cleaned
    }

    /**
     * Emits the markup as a chain of `"…" + "…"` literals: one literal per SVG
     * element keeps every constant far below the 64KB classfile constant-pool
     * limit for a single string.
     */
    private fun emitStringLiteral(sb: StringBuilder, content: String) {
        val parts = content.splitAfter('>')
        val chunk = StringBuilder()
        val lines = mutableListOf<String>()
        fun flush() {
            if (chunk.isEmpty()) return
            lines.add(escape(chunk.toString()))
            chunk.setLength(0)
        }
        for (p in parts) {
            if (chunk.length + p.length > 480) flush()
            chunk.append(p)
        }
        flush()
        sb.append(" ")
        lines.forEachIndexed { i, l ->
            if (i > 0) sb.append("\n ")
            sb.append(if (i == lines.lastIndex) l else "$l +")
        }
    }

    private fun String.splitAfter(sep: Char): List<String> {
        val out = mutableListOf<String>()
        var current = StringBuilder()
        for (c in this) {
            current.append(c)
            if (c == sep) {
                out.add(current.toString())
                current = StringBuilder()
            }
        }
        if (current.isNotEmpty()) out.add(current.toString())
        return out
    }

    private fun escape(s: String): String {
        val sb = StringBuilder("\"")
        for (c in s) when (c) {
            '"' -> sb.append("\\\"")
            '\\' -> sb.append("\\\\")
            '$' -> sb.append("\\$")
            '\n' -> sb.append("\\n")
            '\r' -> sb.append("\\r")
            '\t' -> sb.append("\\t")
            else -> sb.append(c)
        }
        return sb.append('"').toString()
    }

    private fun StringBuilder.line(s: String = "") {
        append(s).append('\n')
    }

    private fun write(fileName: String, content: StringBuilder) {
        val pkgDir = outputDir.asFile.get().resolve(packageName.get().replace('.', File.separatorChar))
        pkgDir.mkdirs()
        val file = pkgDir.resolve(fileName)
        val text = content.toString()
        // Write only on change so Gradle's output-based up-to-date check stays honest.
        if (!file.exists() || file.readText() != text) file.writeText(text)
    }
}
